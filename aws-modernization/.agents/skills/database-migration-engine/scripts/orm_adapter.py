"""Generate ORM configuration files for the target language/framework.

Reads the mapped schema and the engagement target_contract to emit:
  - C# / ASP.NET Core  -> Npgsql EF Core DbContext + connection string snippet
  - Java / Spring Boot -> application.yml + JPA entity stubs
  - Python / FastAPI   -> SQLAlchemy models + database.py

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from db_migration_model import now


# ---------------------------------------------------------------------------
# C# / EF Core (Npgsql)
# ---------------------------------------------------------------------------

_CSHARP_TYPE_MAP: dict[str, str] = {
    "INTEGER":          "int",
    "SMALLINT":         "short",
    "BIGINT":           "long",
    "BOOLEAN":          "bool",
    "TEXT":             "string",
    "UUID":             "Guid",
    "DATE":             "DateOnly",
    "TIME":             "TimeOnly",
    "TIMESTAMP":        "DateTime",
    "TIMESTAMPTZ":      "DateTimeOffset",
    "DOUBLE PRECISION": "double",
    "REAL":             "float",
    "BYTEA":            "byte[]",
    "XML":              "string",
    "JSONB":            "string",
}


def _cs_type(pg_type: str, nullable: bool) -> str:
    base = pg_type.split("(")[0].strip().upper()
    if base.startswith("NUMERIC") or base.startswith("DECIMAL"):
        cs = "decimal"
    elif base.startswith("VARCHAR") or base.startswith("CHAR"):
        cs = "string"
    else:
        cs = _CSHARP_TYPE_MAP.get(base, "string")
    if nullable and cs not in ("string", "byte[]"):
        cs += "?"
    return cs


def _cs_entity(table: dict) -> str:
    class_name = table["name"].replace("_", " ").title().replace(" ", "")
    lines = [
        f"public class {class_name}",
        "{",
    ]
    for col in table.get("columns", []):
        prop_name = col["name"].replace("_", " ").title().replace(" ", "")
        cs_type = _cs_type(col["targetType"], col.get("nullable", True))
        if col.get("primaryKey"):
            lines.append("    [Key]")
        lines.append(f"    public {cs_type} {prop_name} {{ get; set; }}")
    lines.append("}")
    return "\n".join(lines)


def _generate_csharp(mapped: dict, target_engine: str) -> dict[str, str]:
    tables = mapped.get("tables", [])
    entities = "\n\n".join(_cs_entity(t) for t in tables)
    db_sets = "\n".join(
        f"    public DbSet<{t['name'].replace('_',' ').title().replace(' ','')}> "
        f"{t['name'].replace('_',' ').title().replace(' ','')}s => "
        f"Set<{t['name'].replace('_',' ').title().replace(' ','')}>(); "
        for t in tables
    )

    db_context = f"""\
// Generated by database-migration-engine
// Source: {mapped.get('sourceEngine')} | Target: {target_engine}
// Generated: {now()}

using Microsoft.EntityFrameworkCore;

namespace Modernized.Infrastructure.Persistence;

public class ModernDbContext : DbContext
{{
    public ModernDbContext(DbContextOptions<ModernDbContext> options) : base(options) {{ }}

{db_sets}
}}
"""

    connection_snippet = f"""\
// appsettings.json — connection string for {target_engine}
// Replace <host>, <db>, <user>, <password> with your actual values.
{{
  "ConnectionStrings": {{
    "DefaultConnection": "Host=<host>.postgres.database.azure.com;Database=<db>;Username=<user>;Password=<password>;SslMode=Require;"
  }}
}}
"""

    program_snippet = f"""\
// Program.cs — register Npgsql EF Core
// Add NuGet: Npgsql.EntityFrameworkCore.PostgreSQL

builder.Services.AddDbContext<ModernDbContext>(options =>
    options.UseNpgsql(builder.Configuration.GetConnectionString("DefaultConnection")));
"""

    entities_file = f"""\
// Generated by database-migration-engine
// Source: {mapped.get('sourceEngine')} | Target: {target_engine}

using System.ComponentModel.DataAnnotations;

namespace Modernized.Domain.Entities;

{entities}
"""

    return {
        "ModernDbContext.cs": db_context,
        "Entities.cs": entities_file,
        "connection-string.snippet.json": connection_snippet,
        "Program.snippet.cs": program_snippet,
    }


# ---------------------------------------------------------------------------
# Java / Spring Boot (JPA)
# ---------------------------------------------------------------------------

_JAVA_TYPE_MAP: dict[str, str] = {
    "INTEGER":          "Integer",
    "SMALLINT":         "Short",
    "BIGINT":           "Long",
    "BOOLEAN":          "Boolean",
    "TEXT":             "String",
    "UUID":             "java.util.UUID",
    "DATE":             "java.time.LocalDate",
    "TIME":             "java.time.LocalTime",
    "TIMESTAMP":        "java.time.LocalDateTime",
    "TIMESTAMPTZ":      "java.time.OffsetDateTime",
    "DOUBLE PRECISION": "Double",
    "REAL":             "Float",
    "BYTEA":            "byte[]",
    "JSONB":            "String",
}


def _java_type(pg_type: str) -> str:
    base = pg_type.split("(")[0].strip().upper()
    if base.startswith("NUMERIC") or base.startswith("DECIMAL"):
        return "java.math.BigDecimal"
    if base.startswith("VARCHAR") or base.startswith("CHAR"):
        return "String"
    return _JAVA_TYPE_MAP.get(base, "String")


def _java_entity(table: dict) -> str:
    class_name = table["name"].replace("_", " ").title().replace(" ", "")
    table_name = table["name"].lower()
    lines = [
        f'@Entity',
        f'@Table(name = "{table_name}")',
        f'public class {class_name} {{',
    ]
    for col in table.get("columns", []):
        field_name = col["name"].lower()
        java_type = _java_type(col["targetType"])
        if col.get("primaryKey"):
            lines.append("    @Id")
            lines.append('    @GeneratedValue(strategy = GenerationType.IDENTITY)')
        lines.append(f'    @Column(name = "{field_name}")')
        lines.append(f"    private {java_type} {field_name};")
    lines.append("}")
    return "\n".join(lines)


def _generate_java(mapped: dict, target_engine: str) -> dict[str, str]:
    tables = mapped.get("tables", [])
    entities = "\n\n".join(_java_entity(t) for t in tables)

    app_yml = f"""\
# Generated by database-migration-engine
# Source: {mapped.get('sourceEngine')} | Target: {target_engine}
spring:
  datasource:
    url: jdbc:postgresql://<host>.postgres.database.azure.com:5432/<db>?sslmode=require
    username: <user>
    password: <password>
    driver-class-name: org.postgresql.Driver
  jpa:
    hibernate:
      ddl-auto: validate
    properties:
      hibernate:
        dialect: org.hibernate.dialect.PostgreSQLDialect
"""

    entities_file = f"""\
// Generated by database-migration-engine
// Source: {mapped.get('sourceEngine')} | Target: {target_engine}

import jakarta.persistence.*;
import java.math.BigDecimal;

{entities}
"""

    return {
        "application.yml": app_yml,
        "Entities.java": entities_file,
    }


