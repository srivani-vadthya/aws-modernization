_PY_TYPE_MAP: dict[str, str] = {
    "INTEGER":          "Integer",
    "SMALLINT":         "SmallInteger",
    "BIGINT":           "BigInteger",
    "BOOLEAN":          "Boolean",
    "TEXT":             "Text",
    "UUID":             "UUID",
    "DATE":             "Date",
    "TIME":             "Time",
    "TIMESTAMP":        "DateTime",
    "TIMESTAMPTZ":      "DateTime(timezone=True)",
    "DOUBLE PRECISION": "Float",
    "REAL":             "Float",
    "BYTEA":            "LargeBinary",
    "JSONB":            "JSON",
}


def _py_type(pg_type: str) -> str:
    base = pg_type.split("(")[0].strip().upper()
    if base.startswith("NUMERIC") or base.startswith("DECIMAL"):
        parts = pg_type.strip("NUMERIC()DECIMAL()").split(",")
        p, s = (parts + ["18", "2"])[:2]
        return f"Numeric(precision={p.strip()}, scale={s.strip()})"
    if base.startswith("VARCHAR") or base.startswith("CHAR"):
        m = __import__("re").search(r"\((\d+)\)", pg_type)
        length = m.group(1) if m else "255"
        return f"String({length})"
    return _PY_TYPE_MAP.get(base, "Text")


def _py_model(table: dict) -> str:
    class_name = table["name"].replace("_", " ").title().replace(" ", "")
    table_name = table["name"].lower()
    lines = [
        f"class {class_name}(Base):",
        f'    __tablename__ = "{table_name}"',
        "",
    ]
    for col in table.get("columns", []):
        col_name = col["name"].lower()
        py_type = _py_type(col["targetType"])
        kwargs = []
        if col.get("primaryKey"):
            kwargs.append("primary_key=True")
        if not col.get("nullable", True):
            kwargs.append("nullable=False")
        kw_str = ", ".join(kwargs)
        lines.append(f"    {col_name} = Column({py_type}{', ' + kw_str if kw_str else ''})")
    return "\n".join(lines)


def _generate_python(mapped: dict, target_engine: str) -> dict[str, str]:
    tables = mapped.get("tables", [])
    models = "\n\n".join(_py_model(t) for t in tables)

    database_py = f"""\
# Generated by database-migration-engine
# Source: {mapped.get('sourceEngine')} | Target: {target_engine}

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker, declarative_base

DATABASE_URL = "postgresql+psycopg2://<user>:<password>@<host>.postgres.database.azure.com/<db>?sslmode=require"

engine = create_engine(DATABASE_URL)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
"""

    models_py = f"""\
# Generated by database-migration-engine
# Source: {mapped.get('sourceEngine')} | Target: {target_engine}

from sqlalchemy import Column, Integer, SmallInteger, BigInteger, Boolean, Text, String
from sqlalchemy import Numeric, Float, Date, Time, DateTime, LargeBinary, JSON, UUID
from sqlalchemy.orm import declarative_base

Base = declarative_base()


{models}
"""

    return {
        "database.py": database_py,
        "models.py": models_py,
    }


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

def generate_orm(mapped: dict, language: str, framework: str, target_engine: str) -> dict[str, str]:
    lang = language.lower()
    fw = framework.lower()

    if "csharp" in lang or "dotnet" in lang or "aspnet" in fw:
        return _generate_csharp(mapped, target_engine)
    if "java" in lang or "spring" in fw:
        return _generate_java(mapped, target_engine)
    if "python" in lang or "fastapi" in fw or "django" in fw:
        return _generate_python(mapped, target_engine)

    # Default to C# if unknown
    return _generate_csharp(mapped, target_engine)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("schema", help="Path to schema-mapped.json")
    ap.add_argument("--language", default="csharp", help="Target language: csharp, java, python")
    ap.add_argument("--framework", default="aspnetcore", help="Target framework: aspnetcore, spring-boot, fastapi")
    ap.add_argument("--target", default="azure-postgresql", help="Target DB engine label")
    ap.add_argument("--out", default="orm-config", help="Output directory (default: orm-config/)")
    args = ap.parse_args(argv)

    with open(args.schema, encoding="utf-8") as fh:
        mapped = json.load(fh)

    files = generate_orm(mapped, args.language, args.framework, args.target)
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in files.items():
        (out_dir / filename).write_text(content, encoding="utf-8")
        print(f"  wrote {out_dir / filename}")

    print(f"{len(files)} ORM file(s) -> {args.out}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
